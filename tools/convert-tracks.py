"""Convert bacinger/f1-circuits GeoJSON into js/tracks-real.js.

Usage: python3 tools/convert-tracks.py path/to/f1-circuits.geojson
Points become metres on a local flat projection. The first point is the start/finish line.
Tracks are named by location, not by their official circuit names.
"""
import json, math, sys

CC = {'au':'Australia','bh':'Bahrain','cn':'China','es':'Spain','mc':'Monaco','ca':'Canada','fr':'France','at':'Austria',
      'gb':'Great Britain','de':'Germany','hu':'Hungary','be':'Belgium','it':'Italy','sg':'Singapore','ru':'Russia','jp':'Japan',
      'us':'United States','mx':'Mexico','br':'Brazil','ae':'UAE','pt':'Portugal','my':'Malaysia','tr':'Türkiye','nl':'Netherlands',
      'sa':'Saudi Arabia','qa':'Qatar','az':'Azerbaijan','ar':'Argentina','za':'South Africa'}
HUES = ['#38c6ff','#ff5a3c','#46e08a','#ffb23c','#b48cff','#ff6fb1','#2fe0d0','#ffd84a']

def main(src, dst='js/tracks-real.js'):
    d = json.load(open(src, encoding='utf-8'))
    out = []
    for k, f in enumerate(sorted(d['features'], key=lambda f: f['properties']['Location'])):
        p, c = f['properties'], f['geometry']['coordinates']
        if c[0] == c[-1]: c = c[:-1]
        lat0 = sum(x[1] for x in c) / len(c); lon0 = sum(x[0] for x in c) / len(c)
        pts = [[round((x[0]-lon0)*111320*math.cos(math.radians(lat0)), 1), round(-(x[1]-lat0)*110540, 1)] for x in c]
        loc = p['Location'].replace('Spa Francorchamps', 'Spa-Francorchamps').replace('Dix', 'Watkins Glen')
        out.append({'id': p['id'], 'name': loc, 'place': CC.get(p['id'][:2], '') + ' · real-layout replica', 'length': p['length'],
                    'opened': p.get('opened'), 'hue': HUES[k % len(HUES)], 'kind': 'real', 'pts': pts})
    js = ('/* Real circuit layouts converted from bacinger/f1-circuits (MIT License, (c) 2019-2025 Tomislav Bacinger).\n'
          '   Points are metres on a local flat projection; the first point is the start/finish line and points run in race direction.\n'
          '   Tracks are named by location only. See THIRD_PARTY.md. Generated by tools/convert-tracks.py. */\n'
          'window.PW = window.PW || {};\nPW.REAL_CIRCUITS = ' + json.dumps(out, separators=(',', ':'), ensure_ascii=False) + ';\n')
    open(dst, 'w', encoding='utf-8').write(js)
    print(f'Wrote {len(out)} tracks to {dst}')

if __name__ == '__main__':
    main(sys.argv[1])
